// Writes the browser edition's Content-Security-Policy for nginx
// (site/Dockerfile): the policy below, with the hash of every inline script
// the built pages carry (the theme script in <head>), so no inline script
// needs 'unsafe-inline'.
//
//   node site/docker/csp.mjs site/dist > csp.conf
//
// What the site loads from elsewhere, all fetched (connect-src): the Kokoro
// voices and the chat model's weights from Hugging Face (huggingface.co, which
// redirects to its CDNs under hf.co and huggingface.co), and WebLLM's compiled
// model library from raw.githubusercontent.com. WebAssembly (PGlite, ONNX
// Runtime, WebLLM) needs 'wasm-unsafe-eval'; workers start from the site or
// from blob: URLs.

import { createHash } from "node:crypto";
import { readdirSync, readFileSync, statSync } from "node:fs";
import { join } from "node:path";

const dist = process.argv[2] ?? "site/dist";

function htmlFiles(dir) {
  return readdirSync(dir).flatMap((name) => {
    const path = join(dir, name);
    if (statSync(path).isDirectory()) return name === "actors" || name === "assets" ? [] : htmlFiles(path);
    return name.endsWith(".html") ? [path] : [];
  });
}

const hashes = new Set();
for (const file of htmlFiles(dist)) {
  for (const [, attributes, body] of readFileSync(file, "utf8").matchAll(/<script\b([^>]*)>([\s\S]*?)<\/script>/g)) {
    if (/\bsrc=/.test(attributes) || !body.trim()) continue;
    hashes.add(`'sha256-${createHash("sha256").update(body).digest("base64")}'`);
  }
}

const policy = [
  "default-src 'self'",
  `script-src 'self' 'wasm-unsafe-eval' ${[...hashes].sort().join(" ")}`.trim(),
  "style-src 'self' 'unsafe-inline'",
  "img-src 'self' data: blob:",
  "media-src 'self' blob:",
  "font-src 'self' data:",
  "connect-src 'self' https://huggingface.co https://*.huggingface.co https://*.hf.co https://raw.githubusercontent.com",
  "worker-src 'self' blob:",
  "manifest-src 'self'",
  "object-src 'none'",
  "base-uri 'self'",
  "form-action 'self'",
  "frame-ancestors 'none'",
].join("; ");

process.stdout.write(
  `# Generated by site/docker/csp.mjs from the built pages.\nmap "" $troupe_csp {\n    default "${policy}";\n}\n`,
);

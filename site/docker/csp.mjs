// Writes the browser edition's Content-Security-Policy for nginx
// (site/Dockerfile): the policy below, with the hash of every inline script
// the built pages carry (the theme script in <head>), so no inline script
// needs 'unsafe-inline'.
//
//   node site/docker/csp.mjs site/dist > csp.conf
//
// What the site loads from elsewhere, all fetched (connect-src): the Kokoro
// voices and the chat model's weights from Hugging Face (huggingface.co, which
// redirects to its CDNs under hf.co and huggingface.co), and WebLLM's compiled
// model library from raw.githubusercontent.com. WebAssembly (PGlite, ONNX
// Runtime, WebLLM) needs 'wasm-unsafe-eval'; workers start from the site or
// from blob: URLs.

import { createHash } from "node:crypto";
import { readdirSync, readFileSync, statSync } from "node:fs";
import { join } from "node:path";
import { pathToFileURL } from "node:url";

// The 'sha256-…' source of every inline script in a page.
/** @param {string} html @returns {string[]} */
export function inlineScriptHashes(html) {
  const hashes = [];
  for (const [, attributes = "", body = ""] of html.matchAll(/<script\b([^>]*)>([\s\S]*?)<\/script>/g)) {
    if (/\bsrc=/.test(attributes) || !body.trim()) continue;
    hashes.push(`'sha256-${createHash("sha256").update(body).digest("base64")}'`);
  }
  return hashes;
}

// The policy. A <meta> policy (the pages GitHub Pages serves,
// site/vite-plugins.ts) cannot carry frame-ancestors: { frameAncestors: false }.
/** @param {Iterable<string>} hashes @param {{ frameAncestors?: boolean }} [options] @returns {string} */
export function contentSecurityPolicy(hashes, { frameAncestors = true } = {}) {
  return [
    "default-src 'self'",
    `script-src 'self' 'wasm-unsafe-eval' ${[...new Set(hashes)].sort().join(" ")}`.trim(),
    "style-src 'self' 'unsafe-inline'",
    "img-src 'self' data: blob:",
    "media-src 'self' blob:",
    "font-src 'self' data:",
    "connect-src 'self' https://huggingface.co https://*.huggingface.co https://*.hf.co https://raw.githubusercontent.com",
    "worker-src 'self' blob:",
    "manifest-src 'self'",
    "object-src 'none'",
    "base-uri 'self'",
    "form-action 'self'",
    ...(frameAncestors ? ["frame-ancestors 'none'"] : []),
  ].join("; ");
}

/** @param {string} dir @returns {string[]} */
function htmlFiles(dir) {
  return readdirSync(dir).flatMap((name) => {
    const path = join(dir, name);
    if (statSync(path).isDirectory()) return name === "actors" || name === "assets" ? [] : htmlFiles(path);
    return name.endsWith(".html") ? [path] : [];
  });
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const dist = process.argv[2] ?? "site/dist";
  const hashes = htmlFiles(dist).flatMap((file) => inlineScriptHashes(readFileSync(file, "utf8")));
  process.stdout.write(
    `# Generated by site/docker/csp.mjs from the built pages.\nmap "" $troupe_csp {\n    default "${contentSecurityPolicy(hashes)}";\n}\n`,
  );
}
